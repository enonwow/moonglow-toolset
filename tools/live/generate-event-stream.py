"""Regenerate the embedded producer Lua; no tool or game installation required."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def generate():
    lua = " ".join(line.strip() for line in (ROOT / "event-stream.lua").read_text().splitlines()
                   if line.strip() and not line.lstrip().startswith("--"))
    return ('// Generated by tools/live/generate-event-stream.py from event-stream.lua.\n'
            '// NWNX_Redis_XADD omits MAXLEN; the raw Deferred API accepts every argument.\n'
            '#include "nwnx_redis"\n'
            'const string MGLIVE_STREAM_LUA = ' + json.dumps(lua) + ';\n')


if __name__ == "__main__":
    (ROOT / "nwn/mglive_stream.nss").write_text(generate(), encoding="utf-8")
